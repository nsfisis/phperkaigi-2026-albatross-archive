import { faCopy } from "@fortawesome/free-solid-svg-icons";
import { FontAwesomeIcon } from "@fortawesome/react-fontawesome";
import { useState } from "react";

type Props = {
  code: string;
  // Syntax-highlighted HTML of `code`, pre-rendered by shiki.
  html: string;
};

export default function CodeBlock({ code, html }: Props) {
  const [showCopied, setShowCopied] = useState(false);

  const handleCopy = () => {
    navigator.clipboard.writeText(code).then(() => {
      setShowCopied(true);
      setTimeout(() => setShowCopied(false), 3000);
    });
  };

  return (
    <div className="relative">
      {code !== "" && (
        <button
          type="button"
          onClick={handleCopy}
          className="absolute top-2 right-2 z-10 px-2 py-1 bg-white border border-gray-300 rounded shadow-md hover:bg-gray-100 transition-colors"
          title="コードをコピーする"
        >
          <FontAwesomeIcon icon={faCopy} className="text-gray-600" />
          {showCopied && (
            <span className="ml-1 text-xs text-brand-600">Copied!</span>
          )}
        </button>
      )}
      <div
        className="shiki h-full w-full p-2 pr-12 bg-white rounded-lg border border-gray-300 whitespace-pre-wrap break-words"
        // Trusted HTML generated by shiki when the site was archived.
        dangerouslySetInnerHTML={{ __html: html }}
      />
    </div>
  );
}
